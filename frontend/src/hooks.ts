import { useEffect, useState } from "react";

/** Re-render every ``ms`` (for live clocks and accrual). */
export function useTick(ms = 1000) {
  const [, set] = useState(0);
  useEffect(() => {
    const t = setInterval(() => set((n) => n + 1), ms);
    return () => clearInterval(t);
  }, [ms]);
}
